	d.CDT1 = (
		ks_CDT1_E2F
		-kf_GemininCDT1*CDT1*Geminin + kr_GemininCDT1*Geminin_CDT1
		-kd_CDT1_SCF*CDT1*SCF/(Km_CDT1_SCF + CDT1)
		+kd_GemininCDT1_CDH1*Geminin_CDT1*APCC_CDH1/(Km_GemininCDT1_CDH1+Geminin_CDT1)
	) * α

	d.Geminin = (
		+ks_Geminin_E2F
		-kf_GemininCDT1*CDT1*Geminin + kr_GemininCDT1*Geminin_CDT1
		-kd_Geminin_CDH1*Geminin*APCC_CDH1/(Km_Geminin_CDH1+Geminin)
	) * α

	d.Geminin_CDT1 = (
		+kf_GemininCDT1*CDT1*Geminin - kr_GemininCDT1*Geminin_CDT1
		-kd_GemininCDT1_CDH1*Geminin_CDT1*APCC_CDH1/(Km_GemininCDT1_CDH1+Geminin_CDT1)
	) * α

