		kf_APCCCDH1EMI1*APCC_CDH1*EMI1-kr_APCCCDH1EMI1*APCC_CDH1_EMI1
	) * α
	
	d.SCF = (
		ks_SCF_CCNECDK2*CCNE_CDK2
		-kd_SCF_CDH1*APCC_CDH1*SCF/(Km_SCF_CDH1+SCF)
	) * α

	d.ATM = (
		#-kf_ATMp*(KDDS+sig)
		-kf_ATMp*ATM+kr_ATMp*PPase*ATMp
	) * α

	d.ATMp = (
		kf_ATMp*ATM-kr_ATMp*PPase*ATMp
	) * α

	d.Chk2 = (
		-kf_CHK2p*ATMp*Chk2 + kr_CHK2p*PPase*Chk2p
	) * α

	d.Chk2p = (
		kf_CHK2p*ATMp*Chk2 - kr_CHK2p*PPase*Chk2p
	) * α

	d.p53 = (
	+ks_p53	
	-kd_p53 * p53
	-(kf_p53p*Chk2p)*p53+kr_p53p*PPase*p53p
	-kf_p53MDM2*MDM2*p53 + kr_p53MDM2*p53_MDM2
	) * α

	d.p53p = ((kf_p53p*Chk2p)-kr_p53p*PPase*p53p) * α

	d.MDM2 = (
		+ks_MDM2_p53p*p53p
		-kf_p53MDM2*MDM2*p53 + kr_p53MDM2*p53_MDM2
		-kd_MDM2_ATMp*MDM2*ATMp/(Km_MDM2_ATMp+MDM2)
		+kd_p53MDM2*p53_MDM2
	) * α

	d.p53_MDM2 = (
		kf_p53MDM2*MDM2*p53 - kr_p53MDM2*p53_MDM2
		-kd_p53MDM2*p53_MDM2
	) * α

	d.p21 = (
	+ks_p21*p53p
	-kd_p21 * p21
	-kd_p21_SCF*p21*SCF/(Km_p21_SCF + p21)
	-kd_p21_CDC20*p21*CDC20/(Km_p21_CDC20 + p21)
	-kf_p21CCNECDK2*p21*CCNE_CDK2+kr_p21CCNECDK2*p21_CCNE_CDK2
	-kf_p21CCNACDK2*p21*CCNA_CDK2+kr_p21CCNACDK2*p21_CCNA_CDK2
	+3*(kr_p21CCNBCDK1*p21_CCNB_CDK1-kf_p21CCNBCDK1*CCNB_CDK1*p21^3)
	) * α
	
	d.p21_CCNE_CDK2 = (
		kf_p21CCNECDK2*p21*CCNE_CDK2-kr_p21CCNECDK2*p21_CCNE_CDK2
		-kd_p21CCNECDK2_SCF*SCF*p21_CCNE_CDK2/(Km_p21CCNECDK2_SCF+p21_CCNE_CDK2)
		-kd_p21CCNECDK2_CDC20*APCCP_CDC20*p21_CCNE_CDK2/(Km_p21CCNECDK2_CDC20+p21_CCNE_CDK2)
