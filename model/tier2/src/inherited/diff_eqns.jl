	-kr_PTTG1*PPase*PTTG1p/(Kmr_PTTG1+PTTG1p)
	-kd_PTTG1p_CDC20*APCCP_CDC20*PTTG1p/(Km_PTTG1p_CDC20+PTTG1p)) * α
	
	d.LMNA = (-kf_LMNAp*CCNB_CDK1*LMNA+kr_LMNAp*LMNAp) * α
	
	d.LMNAp = (kf_LMNAp*CCNB_CDK1*LMNA-kr_LMNAp*LMNAp) * α
	
	d.EMI1 = (
		kr_EMI1p*EMI1p-kf_EMI1p*Vol_inhibition*PLK1p*EMI1
		+ks_EMI1_E2F*E2F
		-kf_APCCPCDC20EMI1*APCCP_CDC20*EMI1+kr_APCCPCDC20EMI1*APCCP_CDC20_EMI1
		-kf_APCCCDH1EMI1*APCC_CDH1*EMI1+kr_APCCCDH1EMI1*APCC_CDH1_EMI1
