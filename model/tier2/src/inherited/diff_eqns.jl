function modelDiffEq!(d, u, p, t)

	# Have to be same order as state.jl
	# Unpack State Variables
	 CCND, CDK4, CCND_CDK4, CCND_CDK4p, E2F, RB1, RB_E2F, pRB_E2F, ppRB, CCNE, CDK2,
	 CCNE_CDK2, CCNE_CDK2p, CDC25A, CDC25Ap, CCNA, CCNA_CDK2, CCNA_CDK2p, CCNB,
	 CDK1, CCNB_CDK1, CCNB_CDK1p, WEE1, WEE1p, CDC25C, CDC25Cp, p21, p21_CCNB_CDK1,
	 PLK1, PLK1p, APCC, APCCP, PPase, PPaseP, APCC_CDH1, APCCP_CDH1, CDH1, CDH1p,
	 CDC20, CDC20p, APCCP_CDC20, PTTG1, PTTG1p, LMNA, LMNAp, EMI1,
	 EMI1p, APCCP_CDC20_EMI1, APCC_CDH1_EMI1, SCF, 
	 p21_CCNE_CDK2, p21_CCNA_CDK2, ATM, ATMp, Chk2, Chk2p,
	 p53, p53p, MDM2,
	 p53_MDM2, CDT1, Geminin, Geminin_CDT1  = u

	# These have to be in the same order as parameters.jl
	# Unpack Parameter Variables
	kf_CCNDCDK4, kr_CCNDCDK4, kf_CCNDCDK4p, kr_CCNDCDK4p, kf_RBE2F, kr_RBE2F, 
	kf_pRBE2F, kr_pRBE2F, kf_E2F_ppRB, kr_E2F_ppRB, kf_RB,
	kf_CCNECDK2, kr_CCNECDK2, kf_CCNECDK2p, kr_CCNECDK2p, kf_CDC25Ap_1, kf_CDC25Ap_2,
	kr_CDC25Ap, Kmr_CDC25Ap, kf_CCNACDK2, kr_CCNACDK2, kf_CCNACDK2p, kr_CCNACDK2p, kf_CCNBCDK1, 
	kr_CCNBCDK1, kr_CCNBCDK1p_1, kr_CCNBCDK1p_2, kf_CCNBCDK1p_1, kf_CCNBCDK1p_2, kf_PLK1p_1, kf_PLK1p_2, kr_PLK1p, Kmr_PLK1p, 
	kf_WEE1p_1, kf_WEE1p_2, kf_WEE1p_3, kr_WEE1p, Kmr_WEE1p, kf_CDC25Cp_1, kf_CDC25Cp_2, kr_CDC25Cp, Kmr_CDC25Cp,
	kr_p21CCNBCDK1, kf_p21CCNBCDK1, kf_PPase, kr_PPase, kf_PTTG1, kr_PTTG1, Kmr_PTTG1, kf_LMNAp, kr_LMNAp, kf_CDH1p_1, 
	kf_CDH1p_2, kf_CDH1p_3, kf_CDH1p_4, kr_CDH1p, Kmr_CDH1p, kf_CDC20p_1, kf_CDC20p_2, kr_CDC20p, Kmr_CDC20p,
	kf_APCCP_1, kf_APCCP_2, kr_APCCP, Kmr_APCCP, kf_APCCPCDC20, kr_APCCPCDC20, kfd_APCCPCDC20,kfd_APCCCDC20_1, kfd_APCCCDC20_2,
	kf_APCCCDH1p_1, kf_APCCCDH1p_2, kr_APCCCDH1p, Kmr_APCCCDH1p, kf_APCCCDH1, kr_APCCCDH1, kf_APCCCDH1p_3, kr_APCCCDH1p_3, kfd_APCCCDH1_1, 
	kfd_APCCCDH1_2, kfd_APCCPCDH1_1, kfd_APCCPCDH1_2, kr_EMI1p, kf_EMI1p,kf_APCCPCDC20EMI1, kr_APCCPCDC20EMI1, kf_APCCCDH1EMI1, kr_APCCCDH1EMI1,
	kf_p21CCNECDK2, kr_p21CCNECDK2, kf_p21CCNACDK2, kr_p21CCNACDK2, kf_ATMp, kr_ATMp, kf_CHK2p, kr_CHK2p,
	kf_p53p, kr_p53p, kf_p53MDM2, kr_p53MDM2,
	kf_GemininCDT1, kr_GemininCDT1,
	
	ks_CCND, ks_E2F, ks_CCNE_E2F, ks_CCNE_pRBE2F, ks_CDC25A_E2F, ks_CCNA_E2F,
	ks_CCNB_CCNACDK2, ks_WEE1, ks_CDC25C, ks_PLK1, ks_PTTG1,
	ks_CDC20, ks_CDH1, ks_p21, ks_SCF_CCNECDK2, ks_EMI1_E2F, ks_p53, ks_MDM2_p53p,
	ks_CDT1_E2F, ks_Geminin_E2F, ks_RB,

	kd_CCND_SCF, kd_CCNDCDK4_SCF, kd_E2F_CDH1, kd_E2F_SCF, kd_CCNE_SCF, kd_CCNECDK2_SCF,
	kd_CDC25A_CDH1, kd_CDC25A_SCF, kd_CCNA_CDC20, kd_CCNA_CDH1, 
	kd_CCNACDK2_CDC20, kd_CCNACDK2_CDH1,
	kd_CCNB_CDC20, kd_CCNB_CDH1,
	kd_CCNBCDK1p_CDC20, kd_CCNBCDK1p_CDH1, kd_CCNBCDK1_CDC20, kd_CCNBCDK1_CDH1,
	kd_WEE1p_SCF, kd_CDC25C_CDH1, 
	kd_PLK1_CDH1, kd_PTTG1_CDC20, 
	kd_PTTG1p_CDC20, kd_CDC20_CDH1, 
	kd_CDH1p_SCF, 
	kd_p21, 
	kd_p21_SCF, 
	kd_p21_CDC20, 
	kd_p21CCNECDK2_SCF, 
	kd_p21CCNACDK2_SCF, 
	kd_p21CCNBCDK1_SCF, 
	kd_p21CCNECDK2_CDC20, 
	kd_p21CCNACDK2_CDC20, 
	kd_p21CCNBCDK1_CDC20, 
	kd_SCF_CDH1, kd_EMI1p_SCF,
	kd_MDM2_ATMp, kd_p53MDM2, 
	kd_CDT1_SCF, kd_Geminin_CDH1, kd_GemininCDT1_CDH1, kd_RB, kd_E2F,
	kd_RBE2F_CDH1, kd_RBE2F_SCF, kd_p53, 

	Km_CCND_SCF,Km_CCNDCDK4_SCF, Km_E2F_CDH1, Km_E2F_SCF, Km_CCNE_SCF,
	Km_CCNECDK2_SCF,
	Km_CDC25A_CDH1, Km_CDC25A_SCF, Km_CCNA_CDC20, Km_CCNA_CDH1, 
	Km_CCNACDK2_CDC20, Km_CCNACDK2_CDH1, Km_CCNB_CDC20,		
	Km_CCNB_CDH1, Km_CCNBCDK1p_CDC20, Km_CCNBCDK1p_CDH1, Km_CCNBCDK1_CDC20,
	Km_CCNBCDK1_CDH1, Km_WEE1p_SCF, Km_CDC25C_CDH1,
	Km_PLK1_CDH1, Km_PTTG1_CDC20, Km_PTTG1p_CDC20,
	Km_CDC20_CDH1, Km_CDH1p_SCF, 
	Km_SCF_CDH1, Km_EMI1p_SCF, Km_CDT1_SCF, Km_Geminin_CDH1, Km_GemininCDT1_CDH1,
	Km_RBE2F_CDH1, Km_RBE2F_SCF, Km_MDM2_ATMp,
	Km_p21_SCF, 
	Km_p21_CDC20,
	Km_p21CCNECDK2_SCF, 	
	Km_p21CCNACDK2_SCF, 
	Km_p21CCNBCDK1_SCF, 
	Km_p21CCNECDK2_CDC20, 
	Km_p21CCNACDK2_CDC20, 
	Km_p21CCNBCDK1_CDC20,
	ki_PLK1, α, con_VOL, EC50_VOL, n_VOL, con_ABE, EC50_ABE, n_ABE = p

	Inhibition_ABE = 1 - (con_ABE/EC50_ABE)^n_ABE/(1+((con_ABE/EC50_ABE)^n_ABE))
    Vol_inhibition = 1 - (con_VOL/EC50_VOL)^n_VOL/(1+((con_VOL/EC50_VOL)^n_VOL))
    
	# Differential Equations
	d.CCND = (-kf_CCNDCDK4*CCND*CDK4+kr_CCNDCDK4*CCND_CDK4
	+ks_CCND
	-kd_CCND_SCF*SCF*CCND/(Km_CCND_SCF+CCND)) * α
	
	d.CDK4 = (-kf_CCNDCDK4*CCND*CDK4+kr_CCNDCDK4*CCND_CDK4
	+kd_CCNDCDK4_SCF*SCF*CCND_CDK4p/(Km_CCNDCDK4_SCF+CCND_CDK4p)
	+kd_CCNDCDK4_SCF*SCF*CCND_CDK4/(Km_CCNDCDK4_SCF+CCND_CDK4)
	) * α

	d.CCND_CDK4 = (kf_CCNDCDK4*CCND*CDK4-kr_CCNDCDK4*CCND_CDK4
	-kf_CCNDCDK4p*WEE1*CCND_CDK4+kr_CCNDCDK4p*CDC25Ap*CCND_CDK4p
	-kd_CCNDCDK4_SCF*SCF*CCND_CDK4/(Km_CCNDCDK4_SCF+CCND_CDK4)
	) * α
	
	d.CCND_CDK4p = (kf_CCNDCDK4p*WEE1*CCND_CDK4-kr_CCNDCDK4p*CDC25Ap*CCND_CDK4p
	-kd_CCNDCDK4_SCF*SCF*CCND_CDK4p/(Km_CCNDCDK4_SCF+CCND_CDK4p)
	) * α
	
	d.E2F = (ks_E2F
	-kd_E2F_CDH1*APCC_CDH1*E2F/(Km_E2F_CDH1 + E2F) 
	-kd_E2F_SCF*SCF*E2F/(Km_E2F_SCF + E2F)
	-kd_E2F * E2F
	-kf_RBE2F*E2F*RB1+kr_RBE2F*RB_E2F
	+kf_E2F_ppRB*CCNE_CDK2*pRB_E2F-kr_E2F_ppRB*E2F*ppRB
	) * α
	
	d.RB1 = (-kf_RBE2F*E2F*RB1+kr_RBE2F*RB_E2F
	+kf_RB*PPase*ppRB
	+ks_RB 
	-kd_RB*RB1
    +kd_RBE2F_CDH1*APCC_CDH1*RB_E2F/(Km_RBE2F_CDH1 + RB_E2F) 
	+kd_RBE2F_SCF*SCF*RB_E2F/(Km_RBE2F_SCF + RB_E2F)
	) * α

	d.RB_E2F = (kf_RBE2F*E2F*RB1-kr_RBE2F*RB_E2F
	-kf_pRBE2F*Inhibition_ABE*CCND_CDK4*RB_E2F+kr_pRBE2F*pRB_E2F
    -kd_RBE2F_CDH1*APCC_CDH1*RB_E2F/(Km_RBE2F_CDH1 + RB_E2F) 
	-kd_RBE2F_SCF*SCF*RB_E2F/(Km_RBE2F_SCF + RB_E2F)
    ) * α
	
	d.pRB_E2F = (kf_pRBE2F*Inhibition_ABE*CCND_CDK4*RB_E2F-kr_pRBE2F*pRB_E2F
	-kf_E2F_ppRB*CCNE_CDK2*pRB_E2F+kr_E2F_ppRB*E2F*ppRB) * α
	
	d.ppRB = (kf_E2F_ppRB*CCNE_CDK2*pRB_E2F-kr_E2F_ppRB*E2F*ppRB
	-kf_RB*PPase*ppRB
	) * α

	d.CCNE = (ks_CCNE_E2F*E2F
	+ks_CCNE_pRBE2F*pRB_E2F
	-kd_CCNE_SCF*SCF*CCNE/(Km_CCNE_SCF+CCNE)
	-kf_CCNECDK2*CCNE*CDK2+kr_CCNECDK2*CCNE_CDK2
	) * α
	
	d.CDK2 = (-kf_CCNECDK2*CCNE*CDK2+kr_CCNECDK2*CCNE_CDK2
	-kf_CCNACDK2*CCNA*CDK2+kr_CCNACDK2*CCNA_CDK2
	+kd_CCNECDK2_SCF*SCF*CCNE_CDK2/(Km_CCNE_SCF+CCNE_CDK2)
	+kd_CCNECDK2_SCF*SCF*CCNE_CDK2p/(Km_CCNE_SCF+CCNE_CDK2p)
	+kd_CCNACDK2_CDC20*APCCP_CDC20*CCNA_CDK2p/(Km_CCNA_CDC20+CCNA_CDK2p)
	+kd_CCNACDK2_CDH1*APCC_CDH1*CCNA_CDK2p/(Km_CCNA_CDH1+CCNA_CDK2p)
	+kd_CCNACDK2_CDC20*APCCP_CDC20*CCNA_CDK2/(Km_CCNA_CDC20+CCNA_CDK2)
	+kd_CCNACDK2_CDH1*APCC_CDH1*CCNA_CDK2/(Km_CCNA_CDH1+CCNA_CDK2)
	) * α
	
	d.CCNE_CDK2 = (kf_CCNECDK2*CCNE*CDK2-kr_CCNECDK2*CCNE_CDK2
	-kf_CCNECDK2p*WEE1*CCNE_CDK2
	+kr_CCNECDK2p*CDC25Ap*CCNE_CDK2p
	-kf_p21CCNECDK2*p21*CCNE_CDK2+kr_p21CCNECDK2*p21_CCNE_CDK2
	-kd_CCNECDK2_SCF*SCF*CCNE_CDK2/(Km_CCNECDK2_SCF+CCNE_CDK2)
	+kd_p21CCNECDK2_SCF*SCF*p21_CCNE_CDK2/(Km_p21CCNECDK2_SCF+p21_CCNE_CDK2)
	+kd_p21CCNECDK2_CDC20*APCCP_CDC20*p21_CCNE_CDK2/(Km_p21CCNECDK2_CDC20+p21_CCNE_CDK2)
	) * α
	
	d.CCNE_CDK2p = (
	kf_CCNECDK2p*WEE1*CCNE_CDK2
	-kr_CCNECDK2p*CDC25Ap*CCNE_CDK2p
	-kd_CCNECDK2_SCF*SCF*CCNE_CDK2p/(Km_CCNECDK2_SCF+CCNE_CDK2p)
	) * α
	
	d.CDC25A = (kr_CDC25Ap*CDC25Ap/(Kmr_CDC25Ap+CDC25Ap)
	-kf_CDC25Ap_1*CCNA_CDK2*CDC25A
	-kf_CDC25Ap_2*CCNE_CDK2*CDC25A
	+ks_CDC25A_E2F*E2F
	-kd_CDC25A_CDH1*APCC_CDH1*CDC25A/(Km_CDC25A_CDH1+CDC25A)
	-kd_CDC25A_SCF*SCF*CDC25A/(Km_CDC25A_SCF+CDC25A)
	) * α

	d.CDC25Ap = (-kr_CDC25Ap*CDC25Ap/(Kmr_CDC25Ap+CDC25Ap)
	+kf_CDC25Ap_1*CCNA_CDK2*CDC25A
	+kf_CDC25Ap_2*CCNE_CDK2*CDC25A
	) * α
	
	d.CCNA = (ks_CCNA_E2F*E2F
	-kd_CCNA_CDC20*APCCP_CDC20*CCNA/(Km_CCNA_CDC20+CCNA)
	-kd_CCNA_CDH1*APCC_CDH1*CCNA/(Km_CCNA_CDH1+CCNA)
	-kf_CCNACDK2*CCNA*CDK2+kr_CCNACDK2*CCNA_CDK2
	) * α

	d.CCNA_CDK2 = (kf_CCNACDK2*CCNA*CDK2-kr_CCNACDK2*CCNA_CDK2
	-kf_CCNACDK2p*WEE1*CCNA_CDK2
	+kr_CCNACDK2p*CDC25Ap*CCNA_CDK2p
	-kf_p21CCNACDK2*p21*CCNA_CDK2+kr_p21CCNACDK2*p21_CCNA_CDK2
	-kd_CCNACDK2_CDC20*APCCP_CDC20*CCNA_CDK2/(Km_CCNACDK2_CDC20+CCNA_CDK2)
	-kd_CCNACDK2_CDH1*APCC_CDH1*CCNA_CDK2/(Km_CCNACDK2_CDH1+CCNA_CDK2)
	+kd_p21CCNACDK2_SCF*SCF*p21_CCNA_CDK2/(Km_p21CCNACDK2_SCF+p21_CCNA_CDK2)
	+kd_p21CCNACDK2_CDC20*APCCP_CDC20*p21_CCNA_CDK2/(Km_p21CCNACDK2_CDC20+p21_CCNA_CDK2)
	) * α

	d.CCNA_CDK2p = (
	kf_CCNACDK2p*WEE1*CCNA_CDK2
	-kr_CCNACDK2p*CDC25Ap*CCNA_CDK2p
	-kd_CCNACDK2_CDC20*APCCP_CDC20*CCNA_CDK2p/(Km_CCNACDK2_CDC20+CCNA_CDK2p)
	-kd_CCNACDK2_CDH1*APCC_CDH1*CCNA_CDK2p/(Km_CCNACDK2_CDH1+CCNA_CDK2p)
	) * α
	
	d.CCNB = (-kf_CCNBCDK1*CCNB*CDK1+kr_CCNBCDK1*CCNB_CDK1
	+ks_CCNB_CCNACDK2*CCNA_CDK2
	-kd_CCNB_CDC20*APCCP_CDC20*CCNB/(Km_CCNB_CDC20+CCNB)
	-kd_CCNB_CDH1*APCC_CDH1*CCNB/(Km_CCNB_CDH1+CCNB)) * α

	d.CDK1 = (-kf_CCNBCDK1*CCNB*CDK1+kr_CCNBCDK1*CCNB_CDK1
	+kd_CCNBCDK1p_CDC20*APCCP_CDC20*CCNB_CDK1p/(Km_CCNBCDK1p_CDC20+CCNB_CDK1p)
	+kd_CCNBCDK1p_CDH1*APCC_CDH1*CCNB_CDK1p/(Km_CCNBCDK1p_CDH1+CCNB_CDK1p)
	+kd_CCNBCDK1_CDC20*APCCP_CDC20*CCNB_CDK1/(Km_CCNBCDK1_CDC20+CCNB_CDK1)
	+kd_CCNBCDK1_CDH1*APCC_CDH1*CCNB_CDK1/(Km_CCNBCDK1_CDH1+CCNB_CDK1)
	) * α
	
	d.CCNB_CDK1 = (kr_p21CCNBCDK1*p21_CCNB_CDK1-kf_p21CCNBCDK1*CCNB_CDK1*p21^3
	+kf_CCNBCDK1*CCNB*CDK1-kr_CCNBCDK1*CCNB_CDK1
	+(kr_CCNBCDK1p_1*CDC25Cp+kr_CCNBCDK1p_2*CDC25C)*CCNB_CDK1p
	-(kf_CCNBCDK1p_1*WEE1+kf_CCNBCDK1p_2*WEE1p)*CCNB_CDK1
	-kd_CCNBCDK1_CDC20*APCCP_CDC20*CCNB_CDK1/(Km_CCNBCDK1_CDC20+CCNB_CDK1)
	-kd_CCNBCDK1_CDH1*APCC_CDH1*CCNB_CDK1/(Km_CCNBCDK1_CDH1+CCNB_CDK1)
	+kd_p21CCNBCDK1_CDC20*APCCP_CDC20*p21_CCNB_CDK1/(Km_p21CCNBCDK1_CDC20+p21_CCNB_CDK1)
	+kd_p21CCNBCDK1_SCF*SCF*p21_CCNB_CDK1/(Km_p21CCNBCDK1_SCF+p21_CCNB_CDK1)
	) * α

	d.CCNB_CDK1p = (-(kr_CCNBCDK1p_1*CDC25Cp+kr_CCNBCDK1p_2*CDC25C)*CCNB_CDK1p
	+(kf_CCNBCDK1p_1*WEE1+kf_CCNBCDK1p_2*WEE1p)*CCNB_CDK1
	-kd_CCNBCDK1p_CDC20*APCCP_CDC20*CCNB_CDK1p/(Km_CCNBCDK1p_CDC20+CCNB_CDK1p)
	-kd_CCNBCDK1p_CDH1*APCC_CDH1*CCNB_CDK1p/(Km_CCNBCDK1p_CDH1+CCNB_CDK1p)) * α
	
	d.WEE1 = (kr_WEE1p*PPase*WEE1p/(Kmr_WEE1p+WEE1p)
	+ks_WEE1
	-(kf_WEE1p_1*CCNB_CDK1+kf_WEE1p_2*Vol_inhibition*PLK1p+kf_WEE1p_3*CCNA_CDK2)*WEE1) * α
	
	d.WEE1p = (-kr_WEE1p*PPase*WEE1p/(Kmr_WEE1p+WEE1p)
	-kd_WEE1p_SCF*WEE1p * SCF/ (Km_WEE1p_SCF + WEE1p)
	+(kf_WEE1p_1*CCNB_CDK1+kf_WEE1p_2*Vol_inhibition*PLK1p+kf_WEE1p_3*CCNA_CDK2)*WEE1) * α
	
	d.CDC25C = (kr_CDC25Cp*PPase*CDC25Cp/(Kmr_CDC25Cp+CDC25Cp)
	-(kf_CDC25Cp_1*CCNB_CDK1+kf_CDC25Cp_2*Vol_inhibition*PLK1p)*CDC25C
	+ks_CDC25C
	-kd_CDC25C_CDH1*APCC_CDH1*CDC25C/(Km_CDC25C_CDH1+CDC25C)
	) * α
	
	d.CDC25Cp = (-kr_CDC25Cp*PPase*CDC25Cp/(Kmr_CDC25Cp+CDC25Cp)
	+(kf_CDC25Cp_1*CCNB_CDK1+kf_CDC25Cp_2*Vol_inhibition*PLK1p)*CDC25C
	) * α

	d.PLK1 = (-((kf_PLK1p_1*CCNB_CDK1+kf_PLK1p_2*CCNA_CDK2)*PLK1*Vol_inhibition)
	+kr_PLK1p*PPase*PLK1p/(Kmr_PLK1p+PLK1p)
	+ks_PLK1 * E2F *  (1/(1+p53p/ki_PLK1))
	-kd_PLK1_CDH1*APCC_CDH1*PLK1/(Km_PLK1_CDH1+PLK1)) * α

	d.PLK1p = ((kf_PLK1p_1*CCNB_CDK1+kf_PLK1p_2*CCNA_CDK2)*PLK1*Vol_inhibition
	-kr_PLK1p*PPase*PLK1p/(Kmr_PLK1p+PLK1p)
	) * α
	
	d.APCC = (-(kf_APCCP_1*CCNB_CDK1+kf_APCCP_2*Vol_inhibition*PLK1p)*APCC
	+kr_APCCP*PPase*APCCP/(Kmr_APCCP+APCCP)
	+kfd_APCCPCDC20*PPase*APCCP_CDC20
	+(kfd_APCCCDH1_1*CCNB_CDK1+kfd_APCCCDH1_2*Vol_inhibition*PLK1p)*APCC_CDH1
	-kf_APCCCDH1*APCC*CDH1+kr_APCCCDH1*APCC_CDH1
	) * α
	
	d.APCCP = ((kf_APCCP_1*CCNB_CDK1+kf_APCCP_2*Vol_inhibition*PLK1p)*APCC
	-kr_APCCP*PPase*APCCP/(Kmr_APCCP+APCCP)
	-kf_APCCPCDC20*APCCP*CDC20+kr_APCCPCDC20*APCCP_CDC20
	+(kfd_APCCPCDH1_1*CCNB_CDK1+kfd_APCCPCDH1_2*Vol_inhibition*PLK1p)*APCCP_CDH1
	-kf_APCCCDH1p_3*APCCP*CDH1+kr_APCCCDH1p_3*APCCP_CDH1
	+(kfd_APCCCDC20_1*CCNB_CDK1+kfd_APCCCDC20_2*Vol_inhibition*PLK1p)*APCCP_CDC20
	) * α
	
	d.PPase = (kf_PPase*Vol_inhibition*PPaseP-kr_PPase*CCNB_CDK1*PPase
	) * α
	
	d.PPaseP = (-kf_PPase*Vol_inhibition*PPaseP+kr_PPase*CCNB_CDK1*PPase
	) * α
	
	d.APCC_CDH1 = (-(kf_APCCCDH1p_1*CCNB_CDK1+kf_APCCCDH1p_2*Vol_inhibition*PLK1p)*APCC_CDH1
	+kr_APCCCDH1p*PPase*APCCP_CDH1/(Kmr_APCCCDH1p+APCCP_CDH1)
	-(kfd_APCCCDH1_1*CCNB_CDK1+kfd_APCCCDH1_2*Vol_inhibition*PLK1p)*APCC_CDH1
	+kf_APCCCDH1*APCC*CDH1-kr_APCCCDH1*APCC_CDH1
	-kf_APCCCDH1EMI1*APCC_CDH1*EMI1+kr_APCCCDH1EMI1*APCC_CDH1_EMI1
	) * α
	
	d.APCCP_CDH1 = ((kf_APCCCDH1p_1*CCNB_CDK1+kf_APCCCDH1p_2*Vol_inhibition*PLK1p)*APCC_CDH1
	-kr_APCCCDH1p*PPase*APCCP_CDH1/(Kmr_APCCCDH1p+APCCP_CDH1)
	-(kfd_APCCPCDH1_1*CCNB_CDK1+kfd_APCCPCDH1_2*Vol_inhibition*PLK1p)*APCCP_CDH1
	+kf_APCCCDH1p_3*APCCP*CDH1-kr_APCCCDH1p_3*APCCP_CDH1
